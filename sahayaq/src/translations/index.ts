export type Language = 'en' | 'te';

/**
 * Maps dynamic data to translations if available
 */
export const translateData = (data: string, lang: Language): string => {
    if (!data || lang === 'en') return data;

    // 1. Try direct mapping (for names, bios etc)
    if ((translations.te as any)[data]) {
        return (translations.te as any)[data];
    }

    // 2. Try category mapping with prefix
    const key = `cat_${data.replace(/[&]/g, '').replace(/\s+/g, '_')}` as keyof typeof translations.te;
    return translations.te[key] || data;
};
